<?php

namespace App\Support;

/**
 * Приведение номера борта к общему виду, например «S50Z100844MH-02T»:
 *  - без пробелов, заглавными;
 *  - русские буквы-двойники → латиница (М→M, Н→H, Т→T, С→C, …): «s50z100844мн-02т» → «S50Z100844MH-02T»;
 *  - любые тире/подчёркивания → обычный дефис «-»;
 *  - если дефис перед хвостом «02T» забыли — ставим: «S50Z100844MH02T» → «S50Z100844MH-02T»;
 *  - дополнительный хвост сохраняется: «S50z-100-903-мн-02t-008-manet» → «S50Z100903MH-02T-008-MANET».
 */
class BoardNumber
{
    /** Русские буквы, которые на вид совпадают с латинскими. */
    private const TO_LATIN = [
        'А' => 'A', 'В' => 'B', 'Е' => 'E', 'К' => 'K', 'М' => 'M', 'Н' => 'H',
        'О' => 'O', 'Р' => 'P', 'С' => 'C', 'Т' => 'T', 'Х' => 'X', 'У' => 'Y',
    ];

    public static function normalize(?string $value): ?string
    {
        if ($value === null) return null;

        $plain = trim(preg_replace('/\s+/u', ' ', $value));

        $v = strtr(mb_strtoupper(str_replace(' ', '', $plain)), self::TO_LATIN);
        $v = preg_replace('/[‐-―−_.\/-]+/u', '', $v);   // все дефисы/тире/_ . / убираем — дефис ставим сами

        // Номер эталонного вида — в общем виде (S50Z-100844-MH02T → S50Z100844MH-02T).
        // Хвост после основы сохраняем, разбивая на группы цифр/букв через дефис:
        // S50z-100-903-мн-02t-008-manet → S50Z100903MH-02T-008-MANET
        if (preg_match('/^(S\d+Z\d+[A-Z]+)(\d{2}[A-Z])(.*)$/u', $v, $m)) {
            preg_match_all('/\d+|\p{L}+/u', $m[3], $parts);
            return implode('-', array_merge([$m[1], $m[2]], $parts[0]));
        }

        // Другой вид — не трогаем, только убираем лишние пробелы
        return $plain;
    }
}
